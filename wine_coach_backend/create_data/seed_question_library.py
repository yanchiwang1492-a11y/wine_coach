def main() -> None:
    conn = pymysql.connect(
        host=os.getenv("DB_HOST", "localhost"),
        port=int(os.getenv("DB_PORT", 3306)),
        user=os.getenv("DB_USER", "root"),
        password=os.getenv("DB_PASSWORD", ""),
        db=os.getenv("DB_NAME", "wine_coach"),
        charset="utf8mb4",
    )
    cursor = conn.cursor()

    for q in QUESTIONS:
        cursor.execute(
            "INSERT INTO question_library "
            "(question_title, answer, question_type, sales_stage, customer_type, product_category) "
            "VALUES (%s, %s, %s, %s, %s, %s)",
            q,
        )

    conn.commit()
    print(f"已插入 {len(QUESTIONS)} 道题目")
    cursor.close()
    conn.close()
